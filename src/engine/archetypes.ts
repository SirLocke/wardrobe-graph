/**
 * Instantiates concrete candidate garments from the 35 archetypes using the user's derived SeasonPalette.
 */
export function instantiateCandidateArchetypes(profile: BiometricProfile): {
  archetypeId: string;
  garment: Garment;
  rationale: string;
}[] {
  const palette = deriveSeasonPalette(profile);
  const topPower = palette.powerColors.slice(0, 6);
  const topNeutrals = palette.coreNeutrals.slice(0, 4);

  return GARMENT_ARCHETYPE_BLUEPRINTS.map((bp) => {
    const colorPool = bp.paletteSource === 'power' ? topPower : topNeutrals;
    const chosenColor = colorPool[bp.paletteIndex % colorPool.length] || topPower[0];
    const hsl = hexToHsl(chosenColor.hex);
    const colorTemp = classifyColorTemp(hsl);

    const garment: Garment = {
      id: `sandbox_${bp.id}`,
      name: `${bp.baseName} (${chosenColor.name})`,
      category: bp.category,
      subcategory: bp.subcategory,
      colorName: chosenColor.name,
      colorHex: chosenColor.hex,
      hsl,
      colorTemp,
      fit: bp.fit,
      neckline: bp.neckline,
      texture: bp.texture,
      thermalRating: bp.thermalRating,
      formality: bp.formality,
      waterResistant: bp.waterResistant,
      isClean: true,
      isWishlistSandbox: true,
    };

    return {
      archetypeId: bp.id,
      garment,
      rationale: bp.rationaleTemplate,
    };
  });
}
